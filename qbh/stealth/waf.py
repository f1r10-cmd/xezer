"""WAF aşkarlama və adaptiv bypass qərarları (Faza 2.2).

Məqsəd: bir cavabın (status + başlıqlar + gövdə) WAF tərəfindən verildiyini
aşkarlamaq və bunu **qərara** çevirmək:

  * `tamper_for(waf)`    → SQLiEngine üçün sqlmap tamper skriptləri,
  * `encodings_for(waf)` → `payloads.py` bypass matrisi üçün üstünlük sırası,
  * `rate_factor_for(waf)` → nuclei/ffuf kimi subprocess alətləri üçün
    rate/concurrency azaldılması.

**Dürüstlük.** Bu, yalnız aşkarlamadır — heç bir "avtomatik CAPTCHA həlli"
və ya "WAF-ı mütləq aşır" iddiası YOXDUR. Aşkarlama uğursuz olarsa `generic`
qaytarılır (boş/təsdiqsiz nəticə deyil).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass(frozen=True)
class WafSignature:
    """Bir WAF məhsulunun barmaq izi (başlıq / cookie / gövdə)."""

    name: str
    header_re: tuple[str, ...] = ()
    cookie_re: tuple[str, ...] = ()
    body_re: tuple[str, ...] = ()


#: Növbə vacibdir: daha spesifik imzalar əvvəldə.
WAF_SIGNATURES: tuple[WafSignature, ...] = (
    WafSignature(
        "cloudflare",
        header_re=(r"^cloudflare$", r"\bcf-ray\b", r"^cf-cache-status$"),
        cookie_re=(r"^__cfduid$", r"^cf_clearance$", r"^__cf_bm$"),
        body_re=(r"Attention Required!\s*\|\s*Cloudflare",
                 r"cf-error-details", r"__cf_chl_"),
    ),
    WafSignature(
        "akamai",
        header_re=(r"akamaighost", r"^x-akamai", r"akamai-grn"),
        body_re=(r"Reference\s*#\d+\.[0-9a-f]+", r"AkamaiGHost"),
    ),
    WafSignature(
        "fastly",
        header_re=(r"^x-served-by$", r"fastly", r"^x-fastly", r"^x-timer$"),
        body_re=(r"Fastly error", r"Varnish cache server"),
    ),
    WafSignature(
        "imperva",
        header_re=(r"^x-iinfo$", r"imperva"),
        cookie_re=(r"^visid_incap", r"^incap_ses", r"^nlbi_"),
        body_re=(r"Incapsula incident ID", r"_Incapsula_Resource"),
    ),
    WafSignature(
        "aws",
        header_re=(r"awselb", r"^x-amzn-requestid$", r"^x-amz-cf-id$"),
        body_re=(r"AWS WAF", r"Request blocked\.\s*Generated by cloudfront"),
    ),
    WafSignature(
        "sucuri",
        header_re=(r"^x-sucuri-id$", r"^x-sucuri-cache$"),
        body_re=(r"Sucuri WebSite Firewall", r"cloudproxy"),
    ),
    WafSignature(
        "modsecurity",
        header_re=(r"mod_security", r"modsecurity", r"^x-modsec"),
        body_re=(r"ModSecurity", r"Not Acceptable!", r"NAXSI"),
    ),
    WafSignature(
        "generic",
        header_re=(r"^x-waf",),
        body_re=(r"web application firewall", r"access denied",
                 r"you have been blocked", r"<title>403 Forbidden"),
    ),
)


@dataclass
class WafProfile:
    """Aşkarlama nəticəsi (heç vaxt boş "uğur" iddiası vermir)."""

    name: str = "none"
    confidence: float = 0.0
    evidence: list[str] = field(default_factory=list)
    detection_status: int = 0

    @property
    def detected(self) -> bool:
        return self.name not in ("", "none")

    def to_dict(self) -> dict:
        return {"name": self.name, "confidence": round(self.confidence, 2),
                "evidence": list(self.evidence),
                "status": self.detection_status}


def _headers_lower(headers) -> dict[str, str]:
    out: dict[str, str] = {}
    if not headers:
        return out
    for key, value in dict(headers).items():
        out[str(key).lower()] = str(value)
    return out


def _cookies(headers: dict[str, str]) -> str:
    return headers.get("set-cookie", "") or headers.get("cookie", "")


def detect_waf(*, status: int = 0, headers=None, body: str = "") -> WafProfile:
    """Cavabı WAF imzaları ilə tutuşdurur və ən yaxşı uyğunluğu qaytarır.

    Heç bir imza uyğun gəlməzsə `WafProfile(name="none")` qaytarılır — bu
    "WAF yoxdur" DEMƏK DEYİL, yalnız "tanınmadı" mənasındadır.
    """
    hdrs = _headers_lower(headers)
    cookie = _cookies(hdrs)
    text = body or ""
    blob = "\n".join(f"{k}: {v}" for k, v in hdrs.items())

    best = WafProfile(name="none", confidence=0.0, detection_status=status)
    for sig in WAF_SIGNATURES:
        hits: list[str] = []
        for pat in sig.header_re:
            if re.search(pat, blob, re.I | re.M):
                hits.append(f"header~{pat}")
        for pat in sig.cookie_re:
            if cookie and re.search(pat, cookie, re.I):
                hits.append(f"cookie~{pat}")
        for pat in sig.body_re:
            if text and re.search(pat, text, re.I):
                hits.append(f"body~{pat}")
        if not hits:
            continue
        confidence = min(0.4 + 0.2 * len(hits), 0.95)
        if confidence > best.confidence:
            best = WafProfile(name=sig.name, confidence=confidence,
                              evidence=hits, detection_status=status)
    return best


#: WAF → sqlmap tamper skriptləri (deterministik, sınaqdan keçirilə bilən).
TAMPERS: dict[str, tuple[str, ...]] = {
    "cloudflare": ("space2comment", "randomcase", "charencode"),
    "akamai": ("randomcase", "space2comment", "between"),
    "fastly": ("randomcase", "space2comment"),
    "imperva": ("space2comment", "charencode", "randomcase",
                "apostrophemask"),
    "aws": ("randomcase", "space2comment", "percentage"),
    "sucuri": ("space2comment", "charencode"),
    "modsecurity": ("space2comment", "randomcase", "apostrophemask"),
    "generic": ("randomcase",),
}

#: WAF → `payloads.py` matrisində üstün tutulan texnika etiketləri.
PREFERRED_TRICKS: dict[str, tuple[str, ...]] = {
    "cloudflare": ("path-upper", "path-single-encode", "path-mixed-slash",
                   "header-localhost-via-xff", "verb-OPTIONS"),
    "akamai": ("path-single-encode", "path-double-encode",
               "header-x-original-url", "verb-HEAD"),
    "fastly": ("path-double-encode", "path-semicolon", "header-x-rewrite-url"),
    "imperva": ("path-mixed-slash", "path-single-encode",
                "header-x-custom-ip", "verb-POST"),
    "aws": ("path-double-encode", "header-x-forwarded-host", "verb-OPTIONS"),
    "sucuri": ("path-upper", "path-single-encode", "header-x-real-ip"),
    "modsecurity": ("path-mixed-slash", "path-double-encode", "verb-PUT"),
    "generic": ("path-single-encode", "path-mixed-slash", "verb-HEAD"),
}

#: WAF → rate azaltma faktoru (subprocess nuclei/ffuf üçün tövsiyə).
RATE_FACTORS: dict[str, float] = {
    "cloudflare": 0.5,
    "akamai": 0.5,
    "fastly": 0.7,
    "imperva": 0.4,
    "aws": 0.4,
    "sucuri": 0.7,
    "modsecurity": 0.6,
    "generic": 0.6,
}


def tamper_for(waf_name: str) -> list[str]:
    """WAF üçün sqlmap tamper skriptləri (naməlum → boş siyahı)."""
    if not waf_name:
        return []
    return list(TAMPERS.get(str(waf_name).strip().lower(), ()))


def encodings_for(waf_name: str) -> list[str]:
    """WAF üçün üstün tutulan bypass texnika etiketləri (sıra qorunur)."""
    if not waf_name:
        return []
    return list(PREFERRED_TRICKS.get(str(waf_name).strip().lower(), ()))


def rate_factor_for(waf_name: str) -> float:
    """WAF aşkarlandıqda tövsiyə olunan rate faktoru (default 1.0)."""
    if not waf_name:
        return 1.0
    return float(RATE_FACTORS.get(str(waf_name).strip().lower(), 0.75))
